/**
 * 记账功能 - 常量与类型定义
 *
 * 说明：
 * - AccountingCategory：一条分类配置（支出 / 收入），含图标、主题色与匹配关键词。
 * - DEFAULT_CATEGORIES：预置分类种子，基于常见记账场景穷举（餐饮/交通/购物/居住/娱乐/
 *   医疗/教育/通讯/人情 等支出，工资/奖金/理财/兼职/红包/退款 等收入）。分类与关键字
 *   持久化到 SQLite（accounting_categories / accounting_keywords 两表），首次启动若表为空
 *   则批量写入默认数据，用户可在「分类管理」中增删改。
 * - AccountingRecord：一条记账记录，落 SQLite 表 accounting_records。
 */

/** 分类类型：支出 / 收入 */
export type AccountingType = 'expense' | 'income'

/** 单条分类配置 */
export interface AccountingCategory {
  /** 分类名称，唯一标识（同时作为 accounting_categories 表主键） */
  name: string
  /** 支出或收入 */
  type: AccountingType
  /** Lucide 图标名（需在 components/LucideIcon.vue 的 nameMap 中注册） */
  icon: string
  /** 主题强调色（十六进制） */
  color: string
  /** 自动匹配关键词：备注/商户名包含任一关键词即命中该分类 */
  keywords: string[]
  /** 排序序号（仅用于列表顺序，可选） */
  sort?: number
}

/** 单条记账记录 */
export interface AccountingRecord {
  /** 自增主键（插入时无需传） */
  id?: number
  /** 支出 / 收入 */
  type: AccountingType
  /** 金额（元，正数） */
  amount: number
  /** 分类名称，须存在于分类配置 */
  category: string
  /** 备注 / 商户名 */
  note: string
  /** 支付账户：微信 / 支付宝 / 银行卡 / 现金（可选） */
  account?: string
  /** 记账日期 YYYY-MM-DD */
  record_date: string
  /** 创建时间 YYYY-MM-DD HH:mm:ss（插入时由 DB 写入） */
  created_at?: string
  /** 关联的周期账单 id（由周期性账单自动生成时写入，手动记账为空） */
  recurring_id?: number
}

/** SQLite 表名 */
export const ACCOUNTING_TABLE = 'accounting_records'
/** 分类表名（分类配置持久化到数据库，而非 electron-store） */
export const ACCOUNTING_CATEGORIES_TABLE = 'accounting_categories'
/** 关键字表名（每个分类下的自动匹配关键词，独立成表，便于增删改与关联） */
export const ACCOUNTING_KEYWORDS_TABLE = 'accounting_keywords'
/** 月度预算表名（每行 = 某月某分类的预算金额） */
export const ACCOUNTING_BUDGETS_TABLE = 'accounting_budgets'
/** 周期性账单表名（房租 / 订阅等自动记账规则） */
export const ACCOUNTING_RECURRING_TABLE = 'accounting_recurring'

/** 月度总预算在预算表 category 字段中的特殊标识（非真实分类名） */
export const BUDGET_TOTAL_CATEGORY = '_total_'

/** 周期类型：每周 / 每月 / 每年 */
export type RecurringCycle = 'weekly' | 'monthly' | 'yearly'

/** 周期类型 → 中文标签 */
export const RECURRING_CYCLE_LABELS: Record<RecurringCycle, string> = {
  weekly: '每周',
  monthly: '每月',
  yearly: '每年',
}

/** 单条月度预算（持久化到 SQLite 表 accounting_budgets，主键 key = `${month}::${category}`） */
export interface AccountingBudget {
  /** 主键：`YYYY-MM::分类名`（插入时无需传，由 store 组装） */
  key?: string
  /** 预算月份 YYYY-MM */
  month: string
  /** 分类名；BUDGET_TOTAL_CATEGORY 表示该月的总预算 */
  category: string
  /** 预算金额（元） */
  amount: number
  /** 创建时间 YYYY-MM-DD HH:mm:ss */
  created_at?: string
}

/** 单条周期性账单（持久化到 SQLite 表 accounting_recurring，id 自增主键） */
export interface AccountingRecurring {
  /** 自增主键（插入时无需传） */
  id?: number
  /** 账单名称（如 房租 / 视频会员），自动生成的记录备注默认取该名称 */
  name: string
  /** 支出 / 收入 */
  type: AccountingType
  /** 每期金额（元，正数） */
  amount: number
  /** 记账分类名称，须存在于分类配置 */
  category: string
  /** 备注（可选，缺省用 name） */
  note?: string
  /** 支付账户（可选） */
  account?: string
  /** 周期类型：每周 / 每月 / 每年 */
  cycle: RecurringCycle
  /**
   * 执行日（按 cycle 解释，统一存字符串）：
   * - monthly：'1'~'31'（当月无该日则取月末最后一天）
   * - weekly：'1'~'7'（1=周一 … 7=周日）
   * - yearly：'MM-DD'
   */
  day: string
  /** 是否启用（SQLite 存 0/1） */
  enabled: number
  /** 下次执行日期 YYYY-MM-DD（引擎只处理 next_date <= 今天的账单） */
  next_date: string
  /** 最近一次自动记账日期 YYYY-MM-DD */
  last_date?: string
  /** 创建时间 YYYY-MM-DD HH:mm:ss */
  created_at?: string
}

