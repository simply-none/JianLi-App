/** 在查询串里找省级线索（取最长匹配，避免「湖南」被「南」类短名抢走） */
function findProvinceIn(name: string): AreaRecord | null {
  let best: AreaRecord | null = null;
  for (const [key, idx] of PROVINCE_BY_KEY!) {
    if (key.length < 2) continue;
    if (!name.includes(key)) continue;
    const rec = AREAS![idx];
    if (!best || key.length > (best.short.length || best.name.length)) best = rec;
  }
  return best;
}

/** 按条件筛选并排序（知名城市优先 → 名称短者优先），返回下标 */
function sortedAreas(pred: (a: AreaRecord) => boolean): number[] {
  buildIndex();
  const idxs: number[] = [];
  AREAS!.forEach((a, i) => {
    if (pred(a)) idxs.push(i);
  });
  idxs.sort(
    (a, b) => isFamous(b) - isFamous(a) || AREAS![a].name.length - AREAS![b].name.length
  );
  return idxs;
}

