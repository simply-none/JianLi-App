/** 层级编码 */
export const LEVEL_PROVINCE = 1;
export const LEVEL_CITY = 2;
export const LEVEL_DISTRICT = 3;

/** 行政区划记录 */
export interface AreaRecord {
  /** 国家行政区划代码（唯一） */
  adcode: number;
  /** 全名（带「市/区/县」等后缀，如「南康区」） */
  name: string;
  /** 去后缀短名（如「南康」） */
  short: string;
  lng: number;
  lat: number;
  level: number;
  /** 上级下标，-1 表示无上级 */
  parent: number;
}

/** 坐标定位提示（渲染端选定候选后回传，用于跳过名称猜测） */
export interface CoordHint {
  /** 国家行政区划代码（首选，最精确） */
  adcode?: number;
  /** 直接给定坐标（次选） */
  lng?: number;
  lat?: number;
}

/**
 * 城市候选（供渲染端重名下拉选择）。
 * 与 AreaRecord 的区别：候选带了「省 / 市 / 区县」的完整路径，便于展示与区分。
 */
export interface CityCandidate {
  adcode: number;
  /** 全名（如「朝阳区」） */
  name: string;
  /** 去后缀短名（如「朝阳」） */
  short: string;
  level: number;
  lng: number;
  lat: number;
  /** 省级全名（如「吉林省」） */
  province: string;
  /** 省级短名（如「吉林」） */
  provinceShort: string;
  /** 上级地级市全名（省级/地级市自身时为空串） */
  city: string;
  /** 上级地级市短名 */
  cityShort: string;
  /** 展示路径（如「吉林省 · 长春市 · 朝阳区」，自动省略空段） */
  path: string;
}

