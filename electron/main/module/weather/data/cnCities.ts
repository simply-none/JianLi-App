/** 行政区划后缀（按长度降序，保证「自治县」先于「县」被剥离） */
const SUFFIX_RE = /(特别行政区|市辖区|自治区|自治州|自治县|自治旗|地区|盟|矿区|林区|新区|省|市|县|区|旗)$/;

/**
 * 自治区别名：去掉「自治区」后仍带民族名（如「新疆维吾尔」），
 * 需再剥一次民族名才能对上用户日常说法（「新疆」「广西」「宁夏」）。
 */
const AUTONOMOUS_ALIAS: Record<string, string> = {
  内蒙古自治区: '内蒙古',
  广西壮族自治区: '广西',
  西藏自治区: '西藏',
  宁夏回族自治区: '宁夏',
  新疆维吾尔自治区: '新疆',
};

/** 去掉行政区划后缀，得到短名 */
export function toShortName(name: string): string {
  const n = name || '';
  if (AUTONOMOUS_ALIAS[n]) return AUTONOMOUS_ALIAS[n];
  return n.replace(SUFFIX_RE, '');
}

/** 解析后的数据集（懒加载，只建一次） */
let AREAS: AreaRecord[] | null = null;
/** 按全名索引：全名 → 下标数组（可能重名） */
let BY_FULL: Map<string, number[]> | null = null;
/** 按短名索引：短名 → 下标数组 */
let BY_SHORT: Map<string, number[]> | null = null;
/** 按 adcode 索引 */
let BY_ADCODE: Map<number, number> | null = null;
/** 省级索引：省级短名/全名 → 下标 */
let PROVINCE_BY_KEY: Map<string, number> | null = null;
/** 上级下标列表（按下标对齐 AREAS），用于 O(1) 判断归属 */
let PARENT_CHAIN: number[][] | null = null;

function buildIndex(): void {
  if (AREAS) return;
  const list: AreaRecord[] = [];
  for (const line of CITY_TABLE) {
    const parts = line.split(',');
    if (parts.length !== 6) continue;
    list.push({
      adcode: Number(parts[0]),
      name: parts[1],
      short: toShortName(parts[1]),
      lng: Number(parts[2]),
      lat: Number(parts[3]),
      level: Number(parts[4]),
      parent: Number(parts[5]),
    });
  }
  AREAS = list;

  BY_FULL = new Map();
  BY_SHORT = new Map();
  BY_ADCODE = new Map();
  PROVINCE_BY_KEY = new Map();

  list.forEach((a, i) => {
    const f = BY_FULL!.get(a.name);
    if (f) f.push(i);
    else BY_FULL!.set(a.name, [i]);

    // 短名索引：short 与全名不同时额外登记（如「南康」→ 南康区）；
    // 相同时（如「北京」= 北京市）也登记，保证查「北京」能命中
    const s = BY_SHORT!.get(a.short);
    if (s) s.push(i);
    else BY_SHORT!.set(a.short, [i]);

    BY_ADCODE!.set(a.adcode, i);

    if (a.level === LEVEL_PROVINCE) {
      PROVINCE_BY_KEY!.set(a.short || a.name, i);
      PROVINCE_BY_KEY!.set(a.name, i);
    }
  });

  // 预计算每条记录的祖先链（含自身），避免查询时反复回溯
  PARENT_CHAIN = list.map((_, i) => {
    const chain: number[] = [];
    let cur = i;
    let guard = 0;
    while (cur >= 0 && guard++ < 10) {
      chain.push(cur);
      cur = list[cur].parent;
    }
    return chain;
  });
}

/** 全量行政区划（调试 / 遍历用） */
export function getAllAreas(): AreaRecord[] {
  buildIndex();
  return AREAS!;
}

/** 按 adcode 取记录 */
function byAdcode(adcode: number): AreaRecord | null {
  buildIndex();
  const i = BY_ADCODE!.get(adcode);
  return i === undefined ? null : AREAS![i];
}

/**
 * 收集与查询串匹配的候选下标（分层，精确命中优先）
 *
 * tier 越小越优先：0=全名精确  1=短名精确  2=剔除省级线索后的包含匹配
 * @param name 查询串
 * @returns 下标 → tier 的映射（空表示无候选）
 */
function collectCandidates(name: string): Map<number, number> {
  buildIndex();
  const short = toShortName(name);
  const tier = new Map<number, number>();
  const add = (i: number, t: number) => {
    const cur = tier.get(i);
    if (cur === undefined || t < cur) tier.set(i, t);
  };

  for (const i of BY_FULL!.get(name) || []) add(i, 0);
  if (short) for (const i of BY_SHORT!.get(short) || []) add(i, 1);

  // 无精确命中时，剔除省级线索后做包含匹配（如「江西赣州南康区」）
  if (!tier.size) {
    const prov = findProvinceIn(name);
    let rest = name;
    if (prov) rest = name.replace(prov.name, '').replace(prov.short, '');
    for (const key of [rest, toShortName(rest)]) {
      if (key.length < 2) continue;
      for (const i of BY_FULL!.get(key) || []) add(i, 2);
      for (const i of BY_SHORT!.get(key) || []) add(i, 2);
    }
  }
  return tier;
}

/**
 * 候选排序：tier 小优先 → level 大优先 → 祖先含知名城市优先 → 下标小（稳定）
 */
function sortCandidates(list: number[], tier: Map<number, number>): number[] {
  return [...list].sort((a, b) => {
    const ta = tier.get(a)!;
    const tb = tier.get(b)!;
    if (ta !== tb) return ta - tb;
    const la = AREAS![a].level;
    const lb = AREAS![b].level;
    if (la !== lb) return lb - la;
    const fa = isFamous(a);
    const fb = isFamous(b);
    if (fa !== fb) return fb - fa;
    return a - b;
  });
}

/**
 * 取城市坐标。
 *
 * 渲染端传进来的可能是多种形态：
 *   - 省级短名：「江西」「广东」
 *   - 地级市 / 县级短名：「赣州」「南康」
 *   - 全名：「南康区」「于都县」「北京市」
 *   - 带上下文的串：「江西赣州南康区」
 *
 * 消歧策略（区县级有 30 组重名，如「朝阳区」北京/长春各一、「新华区」有 3 个）：
 *   0. **传了 hint**（adcode 或坐标）→ 直接精确命中，跳过一切猜测；
 *   1. 若查询串含省级线索（如「江西」），用它把候选限定在该省内；
 *   2. 候选多个时，取 level 更具体（更大）的；仍并列时知名城市优先；
 *   3. 再并列取下标最小，保证结果稳定。
 *
 * @param city 查询串
 * @param hint 可选定位提示（渲染端选定候选后回传，见 CoordHint）
 * @returns 命中返回 { lat, lon }，未命中返回 null
 */
export function lookupCityCoords(city: string, hint?: CoordHint): { lat: number; lon: number } | null {
  // ---- 0. hint 优先：adcode 最精确，其次直接给坐标 ----
  if (hint) {
    if (typeof hint.adcode === 'number') {
      const rec = byAdcode(hint.adcode);
      if (rec) return { lon: rec.lng, lat: rec.lat };
    }
    if (typeof hint.lng === 'number' && typeof hint.lat === 'number') {
      return { lon: hint.lng, lat: hint.lat };
    }
  }

  const name = (city || '').trim();
  // 单字查询过于模糊（「南」会误配到任意含「南」的城市），直接拒绝
  if (name.length < 2) return null;

  const tier = collectCandidates(name);
  if (!tier.size) return null;

  let list = [...tier.keys()];

  // 用省级线索过滤（同级候选内缩小范围）
  const prov = findProvinceIn(name);
  if (prov) {
    const pIdx = PROVINCE_BY_KEY!.get(prov.short) ?? PROVINCE_BY_KEY!.get(prov.name) ?? -1;
    if (pIdx >= 0) {
      const inProv = list.filter((i) => PARENT_CHAIN![i]!.includes(pIdx));
      if (inProv.length) list = inProv;
    }
  }

  const hit = AREAS![sortCandidates(list, tier)[0]];
  return { lon: hit.lng, lat: hit.lat };
}

/**
 * 解析城市候选列表（供渲染端做重名下拉选择）。
 *
 * 与 lookupCityCoords 的区别：这里返回**全部**同 named 候选（已排序，
 * 最优在前），并附上「省 · 市 · 区县」路径，让用户能区分同名地。
 *
 * @param city 查询串
 * @returns 候选数组（无命中返回空数组）
 */
export function resolveCityCandidates(city: string): CityCandidate[] {
  buildIndex();
  const name = (city || '').trim();
  // 空查询：返回省级（省会 / 直辖市）列表，供搜索框聚焦时的默认建议
  if (!name) return sortedAreas((a) => a.level === LEVEL_PROVINCE).map(toCandidate);
  if (name.length < 2) return [];
  const tier = collectCandidates(name);
  if (!tier.size) return [];

  return sortCandidates([...tier.keys()], tier).map((i) => toCandidate(i));
}

/** 把下标转为带路径的候选对象 */
function toCandidate(i: number): CityCandidate {
  const rec = AREAS![i];
  const chain = PARENT_CHAIN![i]!;

  // 祖先链里找省级与地级市（chain[0] 是自身）
  let prov: AreaRecord | null = null;
  let city: AreaRecord | null = null;
  for (const p of chain) {
    const a = AREAS![p];
    if (a.level === LEVEL_PROVINCE) prov = a;
    else if (a.level === LEVEL_CITY) city = a;
  }

  const parts = [
    prov && prov !== rec ? prov.name : '',
    city && city !== rec ? city.name : '',
  ].filter(Boolean);
  // 补上自身名：省级时 parts 为空 ⇒ 结果为「吉林省」；
  // 地级市时 parts 为省 ⇒ 「吉林省 · 吉林市」；区县同理
  parts.push(rec.name);

  return {
    adcode: rec.adcode,
    name: rec.name,
    short: rec.short,
    level: rec.level,
    lng: rec.lng,
    lat: rec.lat,
    province: prov?.name || '',
    provinceShort: prov?.short || '',
    city: city?.name || '',
    cityShort: city?.short || '',
    path: parts.join(' · '),
  };
}

/** 祖先链（含自身）里是否含知名城市 */
function isFamous(i: number): number {
  for (const p of PARENT_CHAIN![i]!) {
    if (FAMOUS_NAMES.has(AREAS![p].name)) return 1;
  }
  return 0;
}

