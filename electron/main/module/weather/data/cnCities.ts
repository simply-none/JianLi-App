/**
 * 取城市坐标
 * @param city 城市名（可能是「于都」这类县级短名，也可能带「市/县/区」后缀）
 * @returns 命中返回 { lat, lon }，未命中返回 null
 */
export function lookupCityCoords(city: string): { lat: number; lon: number } | null {
  const name = (city || '').trim();
  if (!name) return null;

  // 1. 直接命中
  const direct = CAPITALS[name] || PREFECTURES[name];
  if (direct) return { lon: direct[0], lat: direct[1] };

  // 2. 去行政区划后缀再试
  const stripped = name.replace(/(自治州|自治县|自治旗|地区|盟|矿区|林区|新区|市|县|区)$/, '');
  if (stripped && stripped !== name) {
    const hit = CAPITALS[stripped] || PREFECTURES[stripped];
    if (hit) return { lon: hit[0], lat: hit[1] };
    // 2b. 去后缀后是县级短名（如「南康区」→「南康」）→ 映射到所属地级市
    const parent = COUNTY_TO_PREFECTURE[stripped];
    if (parent) {
      const pc = CAPITALS[parent] || PREFECTURES[parent];
      if (pc) return { lon: pc[0], lat: pc[1] };
    }
  }

  // 3. 本身就是县级短名（渲染端直接传「南康」「于都」）→ 映射到所属地级市
  const parentOfName = COUNTY_TO_PREFECTURE[name];
  if (parentOfName) {
    const pc = CAPITALS[parentOfName] || PREFECTURES[parentOfName];
    if (pc) return { lon: pc[0], lat: pc[1] };
  }

  // 4. 短名匹配：城市名包含表中键（如「江西赣州南康区」含「赣州」）
  //    仅做保守的前缀/包含匹配，避免误配
  for (const [key, coord] of Object.entries(PREFECTURES)) {
    if (name.includes(key) || key.includes(stripped || name)) {
      return { lon: coord[0], lat: coord[1] };
    }
  }
  return null;
}

